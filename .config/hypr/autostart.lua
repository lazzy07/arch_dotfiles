---- AUTOSTART ----
-------------------

-- Runs once when Hyprland starts (the Lua equivalent of exec-once), in this order.
-- Not re-run on config reload.
local autostart = {
    "waybar",
    "awww-daemon",
    "swaync",

    -- Turning off monitors when idle. (Check hypridle.conf) for more details.
    "hypridle",

    -- Authentication keychain
    -- "/usr/lib/polkit-kde-authentication-agent-1",
    "/usr/lib/polkit-gnome/polkit-gnome-authentication-agent-1",

    -- Tablet and monitor
    "~/.config/hypr/scripts/tablet-monitor.sh",

    -- Network + Bluetooth tray applets (GUI connect/pair, shown in waybar tray)
    "nm-applet --indicator",
    "blueman-applet",

    -- Re-apply the last matugen wallpaper (generated by matugen-wall.sh)
    "~/.local/bin/awww-restore.sh",
}

hl.on("hyprland.start", function()
    for _, cmd in ipairs(autostart) do
        hl.exec_cmd(cmd)
    end
end)
